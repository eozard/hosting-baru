-- ============================================================================
-- DATABASE SCHEMA: Sistem Absensi PKL & Pendaftaran (PostgreSQL / Supabase)
-- ============================================================================
-- Dikonversi dari schema LIVE MySQL (database `pkl` di Laragon), bukan dari
-- database_mysql.sql lama yang sudah tertinggal.
--
-- CARA IMPORT DI SUPABASE:
--   1. Buka project Supabase → SQL Editor → New query
--   2. Paste seluruh isi file ini → Run
--   3. (Opsional) Import data: paste isi database_postgres_data.sql → Run
--
-- CATATAN KONVERSI DARI MYSQL:
--   - INT AUTO_INCREMENT      → INTEGER GENERATED BY DEFAULT AS IDENTITY
--   - JSON                    → JSONB
--   - DATETIME / TIMESTAMP    → TIMESTAMP(0) (presisi detik, tanpa timezone;
--                               sesi database di-set Asia/Jakarta oleh server)
--   - TIME                    → TIME(0)
--   - DECIMAL                 → NUMERIC
--   - ON UPDATE CURRENT_TIMESTAMP → trigger set_updated_at()
--   - RLS diaktifkan di semua tabel: akses via Supabase REST (anon key)
--     diblokir; server Express connect sebagai postgres (bypass RLS).
--
-- PERBAIKAN: tabel `certificates` disesuaikan dengan kode mentor.js
--   (tambah file_url; nomor_sertifikat & periode jadi nullable).
-- ============================================================================

