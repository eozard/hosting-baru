  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tugas_id INTEGER NOT NULL,
  student_nama VARCHAR(255) NOT NULL,
  kelompok VARCHAR(100) NOT NULL,
  catatan_mahasiswa TEXT DEFAULT NULL,
  file_url VARCHAR(500) DEFAULT NULL,
  link_url VARCHAR(500) DEFAULT NULL,
  nilai NUMERIC(5,2) DEFAULT NULL,
  status VARCHAR(50) NOT NULL DEFAULT 'submitted',
  catatan_mentor TEXT DEFAULT NULL,
  submitted_at TIMESTAMP(0) NOT NULL,
  reviewed_at TIMESTAMP(0) DEFAULT NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
