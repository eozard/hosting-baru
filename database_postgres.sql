-- ----------------------------------------------------------------------------
-- TRIGGER FUNCTION: updated_at otomatis (pengganti ON UPDATE CURRENT_TIMESTAMP)
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ============================================================================
-- TABLE: users
-- ============================================================================
CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama VARCHAR(255) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(50) NOT NULL DEFAULT 'mahasiswa',
  kelompok VARCHAR(100) DEFAULT NULL,
  devices JSONB DEFAULT NULL,
  max_devices INTEGER NOT NULL DEFAULT 2,
  created_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================================
-- TABLE: attendances
-- Berisi absensi (status='hadir') DAN pengajuan izin (status='izin').
-- ============================================================================
CREATE TABLE attendances (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama VARCHAR(255) NOT NULL,
  kelompok VARCHAR(100) DEFAULT NULL,
  tanggal DATE NOT NULL,
  sesi VARCHAR(20) NOT NULL,
  jam_masuk TIME(0) NOT NULL,
  login_time TIMESTAMP(0) NOT NULL,
  status VARCHAR(50) NOT NULL DEFAULT 'hadir',
  keterangan TEXT DEFAULT NULL,
  bukti_url VARCHAR(500) DEFAULT NULL,
  status_approval VARCHAR(50) DEFAULT 'pending',
  approved_by VARCHAR(255) DEFAULT NULL,
  approved_at TIMESTAMP(0) DEFAULT NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_attendances_nama_tanggal_sesi UNIQUE (nama, tanggal, sesi)
);
CREATE INDEX idx_attendances_nama ON attendances (nama);
CREATE INDEX idx_attendances_tanggal ON attendances (tanggal);
CREATE INDEX idx_attendances_status ON attendances (status);
CREATE INDEX idx_attendances_status_approval ON attendances (status_approval);
CREATE INDEX idx_attendances_kelompok ON attendances (kelompok);

-- ============================================================================
-- TABLE: device_bindings
-- Setiap device (browser fingerprint) hanya bisa terikat ke satu user.
-- ============================================================================
CREATE TABLE device_bindings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id VARCHAR(255) NOT NULL UNIQUE,
  user_name VARCHAR(255) NOT NULL,
  kelompok VARCHAR(100) DEFAULT NULL,
  bound_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_used TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  usage_count INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX idx_device_bindings_user ON device_bindings (user_name);
CREATE INDEX idx_device_bindings_device ON device_bindings (device_id);

-- ============================================================================
-- TABLE: logbook
-- Catatan kegiatan harian mahasiswa (1 per hari per user).
-- ============================================================================
CREATE TABLE logbook (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER DEFAULT NULL,
  nama VARCHAR(255) NOT NULL,
  kelompok VARCHAR(100) DEFAULT NULL,
  tanggal DATE NOT NULL,
  kegiatan TEXT NOT NULL,
  kendala TEXT DEFAULT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'draft',
  edit_count INTEGER NOT NULL DEFAULT 0,
  submitted_at TIMESTAMP(0) DEFAULT NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_logbook_nama_tanggal UNIQUE (nama, tanggal),
  CONSTRAINT fk_logbook_user FOREIGN KEY (user_id)
    REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX idx_logbook_user_id ON logbook (user_id);
CREATE INDEX idx_logbook_nama ON logbook (nama);
CREATE INDEX idx_logbook_tanggal ON logbook (tanggal);
CREATE INDEX idx_logbook_status ON logbook (status);
CREATE INDEX idx_logbook_kelompok ON logbook (kelompok);
CREATE TRIGGER trg_logbook_updated_at BEFORE UPDATE ON logbook
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ============================================================================
-- TABLE: pendaftar
-- Pendaftaran peserta PKL publik.
-- ============================================================================
CREATE TABLE pendaftar (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama VARCHAR(255) NOT NULL,
  nim VARCHAR(50) NOT NULL,
  email VARCHAR(255) NOT NULL,
  divisi_pilihan VARCHAR(100) NOT NULL,
  divisi_assigned VARCHAR(100) DEFAULT NULL,
  status VARCHAR(50) NOT NULL DEFAULT 'pending',
  urutan INTEGER NOT NULL,
  assigned_at TIMESTAMP(0) DEFAULT NULL,
  assigned_by VARCHAR(255) DEFAULT NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_pendaftar_urutan ON pendaftar (urutan);
CREATE INDEX idx_pendaftar_status ON pendaftar (status);
CREATE INDEX idx_pendaftar_nim ON pendaftar (nim);
CREATE INDEX idx_pendaftar_email ON pendaftar (email);
CREATE INDEX idx_pendaftar_divisi_assigned ON pendaftar (divisi_assigned);

-- ============================================================================
-- TABLE: pendaftar_files
-- Metadata file PDF (CV, transkrip, surat persetujuan).
-- File fisik disimpan di server/uploads/ (Railway Volume saat production).
-- ============================================================================
CREATE TABLE pendaftar_files (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pendaftar_id INTEGER NOT NULL,
  tipe VARCHAR(50) NOT NULL,
  filename VARCHAR(255) NOT NULL,
  original_name VARCHAR(255) NOT NULL,
  file_size INTEGER DEFAULT NULL,
  mime_type VARCHAR(100) DEFAULT NULL,
  storage_path VARCHAR(500) DEFAULT NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_pendaftar_files_pendaftar FOREIGN KEY (pendaftar_id)
    REFERENCES pendaftar (id) ON DELETE CASCADE
);
CREATE INDEX idx_pendaftar_files_pendaftar ON pendaftar_files (pendaftar_id);

-- ============================================================================
-- TABLE: admin_pendaftaran
-- Akun admin untuk dashboard /admin_pendaftaran (terpisah dari users).
-- ============================================================================
CREATE TABLE admin_pendaftaran (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(100) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  nama VARCHAR(255) NOT NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_admin_pendaftaran_username ON admin_pendaftaran (username);

-- ============================================================================
-- TABLE: holidays
-- Tanggal merah / libur nasional.
-- ============================================================================
CREATE TABLE holidays (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tanggal DATE NOT NULL UNIQUE,
  keterangan VARCHAR(255) NOT NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_holidays_tanggal ON holidays (tanggal);

-- ============================================================================
-- TABLE: grading_indicators
-- Indikator penilaian dinamis buatan mentor.
-- ============================================================================
CREATE TABLE grading_indicators (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mentor_nama VARCHAR(255) NOT NULL,
  kelompok VARCHAR(100) NOT NULL,
  nama_indikator VARCHAR(255) NOT NULL,
  bobot NUMERIC(5,2) NOT NULL DEFAULT 0,
  urutan INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_grading_indicators_mentor ON grading_indicators (mentor_nama);
CREATE INDEX idx_grading_indicators_kelompok ON grading_indicators (kelompok);

-- ============================================================================
-- TABLE: student_grades
-- Nilai per mahasiswa per indikator.
-- ============================================================================
CREATE TABLE student_grades (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  indicator_id INTEGER NOT NULL,
  student_nama VARCHAR(255) NOT NULL,
  nilai NUMERIC(5,2) DEFAULT NULL,
  catatan TEXT DEFAULT NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_grade UNIQUE (indicator_id, student_nama),
  CONSTRAINT fk_student_grades_indicator FOREIGN KEY (indicator_id)
    REFERENCES grading_indicators (id) ON DELETE CASCADE
);
CREATE INDEX idx_student_grades_student ON student_grades (student_nama);
CREATE TRIGGER trg_student_grades_updated_at BEFORE UPDATE ON student_grades
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ============================================================================
-- TABLE: certificates
-- Data sertifikat per mahasiswa.
-- PERBAIKAN: file_url ditambahkan & kolom nomor/periode jadi nullable
-- agar cocok dengan INSERT di mentor.js (fitur upload sertifikat).
-- ============================================================================
CREATE TABLE certificates (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_nama VARCHAR(255) NOT NULL,
  mentor_nama VARCHAR(255) NOT NULL,
  kelompok VARCHAR(100) NOT NULL,
  nomor_sertifikat VARCHAR(100) DEFAULT NULL UNIQUE,
  judul VARCHAR(255) NOT NULL DEFAULT 'Sertifikat Praktik Kerja Lapangan',
  periode_mulai DATE DEFAULT NULL,
  periode_selesai DATE DEFAULT NULL,
  tanggal_terbit DATE DEFAULT NULL,
  file_url VARCHAR(500) DEFAULT NULL,
  catatan TEXT DEFAULT NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_certificates_student ON certificates (student_nama);
CREATE INDEX idx_certificates_mentor ON certificates (mentor_nama);
CREATE INDEX idx_certificates_kelompok ON certificates (kelompok);

-- ============================================================================
-- TABLE: tugas_akhir
